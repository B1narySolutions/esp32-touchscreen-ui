#!/bin/bash
# Builds and runs amp_sim: the Seed's amp code on the Mac, controlled by the real touchscreen.
#
#   bash tools/amp_sim/run.sh                       finds the touchscreen's USB TO UART port
#   bash tools/amp_sim/run.sh /dev/cu.usbmodemXXXX --input guitar.wav --seconds 120
#   bash tools/amp_sim/run.sh --demo                 before/after clips of every amp knob, measured
#
# Setup: touchscreen SW1 on UART1 and its "USB TO UART" port plugged into the Mac (that's where
# its link goes on UART1). Rocco's realtime-nam-seed3 is cloned at the commit the Seed build uses
# (seed3-link-firmware/build.sh) into build/amp-sim/ and never changed. Output: the console, the
# Mac's speakers, and build/amp-sim/amp_sim_output.wav.
set -euo pipefail
root="$(cd "$(dirname "$0")/../.." && pwd)"
work="$root/build/amp-sim"
seed_commit=$(sed -n 's/^seed_commit=//p' "$root/seed3-link-firmware/build.sh")
mkdir -p "$work"

# 1. Rocco's code at the pinned commit, and the three amp models baked into a header.
seed="$work/realtime-nam-seed3"
if [[ ! -d "$seed/.git" ]]; then
    git clone -q https://github.com/B1narySolutions/realtime-nam-seed3.git "$seed"
fi
if [[ "$(git -C "$seed" rev-parse HEAD)" != "$seed_commit" ]]; then
    git -C "$seed" fetch -q origin
    git -C "$seed" checkout -q --detach "$seed_commit"
fi
if [[ ! -f "$seed/models/local/marshall-jcm800-g5-a2-lite.nam" ]]; then
    (cd "$seed" && bash scripts/download_models.sh)
fi
if [[ ! -f "$seed/build/generated/embedded_a2_data.h" ]]; then
    (cd "$seed" && python3 -B scripts/convert_a2.py header build/generated/embedded_a2_data.h)
fi

# 2. Parameter names for the console, from the generated id header.
proto="$root/firmware/main/seed_link_proto"
python3 - "$proto/slp_params.h" "$work/param_names.h" <<'PY'
import re, sys
rows = re.findall(r'#define SLP_P_(\w+)\s+(0x[0-9A-Fa-f]+)', open(sys.argv[1]).read())
with open(sys.argv[2], 'w') as f:
    f.write('// Generated by tools/amp_sim/run.sh from slp_params.h.\n#pragma once\n#include <cstdint>\n')
    f.write('inline const char *ParamName(uint16_t id) {\n    switch (id) {\n')
    for name, value in rows:
        f.write(f'    case {value}: return "{name}";\n')
    f.write('    default: return "?";\n    }\n}\n')
PY

# 3. Build: Rocco's audio sources as his host tests build them, plus the Seed-side receiver.
src="$seed/src"
dsp="$root/seed-dsp"
if [[ ! -x "$work/amp_sim" || "$root/tools/amp_sim/amp_sim.cpp" -nt "$work/amp_sim" || "$proto/slp_receiver.c" -nt "$work/amp_sim" \
      || "$dsp/amp_controls.cpp" -nt "$work/amp_sim" || "$dsp/amp_controls.h" -nt "$work/amp_sim" ]]; then
    echo "Building amp_sim..."
    clang -std=c99 -O2 -c "$proto/seed_link_proto.c" -o "$work/seed_link_proto.o"
    clang -std=c99 -O2 -c "$proto/slp_receiver.c" -I"$proto" -o "$work/slp_receiver.o"
    clang++ -std=c++20 -O2 -Wall -I"$src" -I"$seed/build/generated" -I"$proto" -I"$work" -I"$dsp" \
        "$root/tools/amp_sim/amp_sim.cpp" "$dsp/amp_controls.cpp" "$src/audio/nam_audio.cpp" "$src/audio/cab_filter.cpp" \
        "$src/audio/output_controls.cpp" "$src/audio/nam_processor.cpp" "$src/models/amp_models.cpp" \
        "$src/models/a2_lite.cpp" "$work/seed_link_proto.o" "$work/slp_receiver.o" \
        -framework AudioToolbox -framework CoreFoundation -o "$work/amp_sim"
fi

# 4. The touchscreen's USB TO UART port (CH343, USB id 1a86) unless one was given.
args=("$@")
demo=0
for a in "${args[@]}"; do [[ "$a" == --demo ]] && demo=1; done
if [[ $demo -eq 0 && ( ${#args[@]} -eq 0 || "${args[0]}" == --* ) ]]; then
    port=""
    for py in "$HOME"/.espressif/python_env/*/bin/python python3; do
        port=$("$py" -c 'import serial.tools.list_ports as l
for p in l.comports():
    if p.vid == 0x1a86: print(p.device); break' 2>/dev/null) && [[ -n "$port" ]] && break
    done
    if [[ -z "$port" ]]; then
        echo "Can't find the touchscreen's USB TO UART port. Plug it in (SW1 on UART1), or give the port." >&2
        ls /dev/cu.usbmodem* 2>/dev/null >&2 || true
        exit 1
    fi
    args=("$port" "${args[@]}")
fi
cd "$work"
exec "$work/amp_sim" "${args[@]}" --out "$work"
